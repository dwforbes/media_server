/// The first-line marker distinguishing our generated sidecars from
/// hand-written ones we must never clobber.
const MARKER: &str = "generated by media-enrich";

#[derive(Parser)]
#[command(about = "Writes Kodi-style .nfo sidecars for movies from TMDB. \
Re-runnable: by default only files missing an .nfo are enriched.")]
struct Args {
    /// The scanner's config file; its movies roots are enriched.
    #[arg(long, default_value = "media-scanner.toml")]
    config: PathBuf,
    /// TMDB API key (v3 key or v4 read token). Falls back to $TMDB_API_KEY.
    #[arg(long)]
    api_key: Option<String>,
    /// Also re-fetch .nfo files this tool generated earlier (data changes).
    #[arg(long)]
    refresh: bool,
    /// With --refresh: overwrite hand-written .nfo files too.
    #[arg(long)]
    force: bool,
    /// Show what would happen without any network calls or writes.
    #[arg(long)]
    dry_run: bool,
    /// Skip downloading poster images.
    #[arg(long)]
    no_posters: bool,
    /// Skip IMDb ratings.
    #[arg(long)]
    no_ratings: bool,
    /// Neutralize embedded container titles in video files (also enabled by
    /// strip_titles = true in the config's [enrich] section).
    #[arg(long)]
    strip_titles: bool,
    /// Embed same-name .srt sidecars into subtitle-less MP4s, and re-embed
    /// when a sidecar embedded earlier has changed (also enabled by
    /// embed_subtitles = true in the config's [enrich] section).
    #[arg(long)]
    embed_subtitles: bool,
    /// Remux MKV files to MP4 (stream copy; AC-3/E-AC-3 audio gains a stereo
    /// AAC twin). Also enabled by remux_mkv = true in the [enrich] section.
    #[arg(long)]
    remux_mkv: bool,
    /// Skip extracting embedded text subtitle tracks to .srt sidecars (on
    /// by default; also disabled by extract_subtitles = false in [enrich]).
    #[arg(long)]
    no_extract_subtitles: bool,
    /// Leave hev1-tagged HEVC MP4s alone (on by default; also disabled by
    /// fix_hevc_tags = false in [enrich]). Normally they are retagged hvc1
    /// in place, which is what Safari, QuickTime and iOS need to play them.
    #[arg(long)]
    no_fix_hevc_tags: bool,
    /// With subtitle embedding: an MP4 whose single caption track carries no
    /// record and says something other than its .srt sidecar normally keeps
    /// its track; this says the sidecar wins and re-embeds it. A one-off for
    /// libraries whose sidecars were corrected before records existed.
    #[arg(long)]
    adopt_sidecar_captions: bool,
    /// Give newly arrived videos whose audio is mastered far below the
    /// rest a louder default track (a linear gain within the track's own
    /// headroom; the original stays behind it). Also enabled by
    /// normalize_loudness = true in the [enrich] section.
    #[arg(long)]
    normalize_loudness: bool,
    /// Measure (and, when it qualifies, normalize) this file or folder
    /// now, whenever it arrived. Repeatable. Works without
    /// --normalize-loudness, and with --dry-run to see the numbers only.
    #[arg(long, value_name = "PATH")]
    loudness_path: Vec<PathBuf>,
    /// Re-download the cached IMDb ratings dataset when older than this.
    #[arg(long, default_value_t = 7)]
    ratings_max_age_days: u64,
    /// Pause between movies, to stay polite to the API.
    #[arg(long, default_value_t = 300)]
    delay_ms: u64,
}

